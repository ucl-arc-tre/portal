import { useState } from "react";
import { Asset, AssetBase, getStudiesByStudyIdAssets, postStudiesByStudyIdAssets, Study } from "@/openapi";
import { extractErrorMessage, responseIsError } from "@/lib/errorHandler";
import { useAuth } from "@/hooks/useAuth";

import AssetCreationForm from "./AssetCreationForm";
import Button from "@/components/ui/Button";
import AssetCard from "./AssetCard";

import styles from "./Assets.module.css";
import { InfoIcon } from "../ui/uikitExports";
import Box from "../ui/Box";
import ErrorMessage from "../ui/Error";
import { AssetDefinition } from "../shared/entityDefinitions";
import HelperBlock from "../ui/HelperBlock";

const helperText = `Use this tab to register and manage the Assets for this Study.  This includes any datasets, documents or information used or generated by the research, such as participant data, consent forms, questionnaires, interview recordings or research databases.
`;

const tellMeMore = (
  <>
    For each Asset, record its classification, storage arrangements and retention requirements and contract
    requirements. Research data containing personal data or special category data should be classified as Highly
    Confidential. Any outstanding actions are highlighted with a warning icon below. <br></br>
    Assets should be reviewed periodically to ensure they remain accurate and required. You may receive reminders when
    asset reviews are due. As part of the review, consider whether the asset is still needed, whether it remains
    appropriately classified and stored, and whether the legal basis for retaining it continues to apply. <br></br>
    Where an asset receives a Vulnerable (Amber) or Critical (Red) risk rating, the identified risks and mitigations
    should be carefully considered. Consider whether changes to storage arrangements, data flows, retention
    arrangements, or access permissions could further protect the information and reduce the likelihood or impact of an
    incident.
  </>
);

type AssetsProps = {
  study: Study;
  assets: Asset[];
  setAssets: (assets: Asset[]) => void;
};

export default function Assets(props: AssetsProps) {
  const { study, assets, setAssets } = props;
  const { userData, isIGAdmin, isIAO, isIGStaff } = useAuth();

  const isStudyOwner = isIAO && study.owner_username === userData?.username;
  const isStudyAdmin = (userData && study.additional_study_admin_usernames.includes(userData.username)) ?? false;
  const canModify = isStudyOwner || isStudyAdmin || isIGAdmin;
  const [infoCalloutExpanded, setInfoCalloutExpanded] = useState(false);

  const [error, setError] = useState<string | null>(null);
  const [showAssetForm, setShowAssetForm] = useState(false);

  const handleAssetSubmit = async (assetData: AssetFormData) => {
    setError(null);

    const response = await postStudiesByStudyIdAssets({
      path: { studyId: study.id },
      body: assetData as AssetBase,
    });

    if (responseIsError(response)) {
      const errorMsg = extractErrorMessage(response);
      throw new Error(errorMsg);
    }

    // Refresh assets list after successful creation
    const updatedAssetsResult = await getStudiesByStudyIdAssets({ path: { studyId: study.id } });
    if (responseIsError(updatedAssetsResult) || !updatedAssetsResult.data) {
      const errorMsg = extractErrorMessage(updatedAssetsResult);
      setError(`Failed to refresh asset list: ${errorMsg}`);
      return;
    }

    setAssets(updatedAssetsResult.data);
    setShowAssetForm(false);
  };

  return (
    <Box>
      <HelperBlock text={helperText} tellMeMore={tellMeMore} />

      <section data-cy="study-assets">
        <div className={styles.header}>
          <h3>
            Asset Management{" "}
            <Button
              onClick={() => setInfoCalloutExpanded(!infoCalloutExpanded)}
              variant="tertiary"
              size="small"
              inline
              aria-label="Toggle asset definition"
              aria-expanded={infoCalloutExpanded}
            >
              <InfoIcon />
            </Button>
          </h3>
          {canModify && assets.length > 0 && (
            <>
              <Button
                onClick={() => setShowAssetForm(!showAssetForm)}
                variant="secondary"
                size="small"
                data-cy="add-asset-button"
              >
                {showAssetForm ? "Cancel" : "Add Asset"}
              </Button>

              {showAssetForm && (
                <AssetCreationForm handleAssetSubmit={handleAssetSubmit} closeModal={() => setShowAssetForm(false)} />
              )}
            </>
          )}
        </div>
        {error && <ErrorMessage message={error} />}

        {infoCalloutExpanded && <AssetDefinition />}

        {assets.length === 0 && canModify ? (
          <div>
            <div className={styles["no-assets-message"]}>
              <p>No assets have been created for this study yet.</p>
              <Button onClick={() => setShowAssetForm(true)} variant="primary" data-cy="add-asset-button">
                Add First Asset
              </Button>
            </div>

            {showAssetForm && (
              <AssetCreationForm handleAssetSubmit={handleAssetSubmit} closeModal={() => setShowAssetForm(false)} />
            )}
          </div>
        ) : (
          <div className={styles["assets-grid"]}>
            {assets.map((asset) => (
              <AssetCard key={asset.id} studyId={study.id} asset={asset} isIGStaff={isIGStaff} />
            ))}
          </div>
        )}
      </section>
    </Box>
  );
}
